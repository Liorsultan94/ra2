#!/usr/bin/env node
/*
 * GD4: pack the Blender-baked desert rock set for the game (tools/blender/rockface.py + rockkit.py).
 *
 *   node tools/blender/rocks-pack.mjs <bake_dir>        (from web/; bake-rocks.sh runs all the steps)
 *
 * <bake_dir>/<key>_{a,n}_<px>.png -> public/tex/terrain/<px>/<key>_{a,n}.webp (512 = phones / medium, 1024 = high),
 * the photoscans' packing and folders (tools/bake-terrain.mjs);
 * <bake_dir>/rockkit-raw.glb -> public/tex/rocks/rockkit.glb (welded, quantised, EXT_meshopt_compression);
 * and writes src/render/rockset.ts: mean colour, roughness and download sizes.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS, EXTMeshoptCompression } from '@gltf-transform/extensions';
import { dedup, prune, quantize, weld } from '@gltf-transform/functions';
import { MeshoptEncoder } from 'meshoptimizer';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const BAKE = process.argv[2];
if (!BAKE) throw new Error('usage: rocks-pack.mjs <bake_dir>');
const SIZES = [512, 1024];
/** Map tiles per texture repeat (the game's triplanar scale; also the ground layer's repeat for the granite). */
const MATS = [
  { key: 'dgranite', tiles: 4.2, note: 'South Sinai granite: joint blocks, exfoliation sheets, cracks, varnish (Blender, tools/blender/rockface.py)' },
  { key: 'dsandst', tiles: 2.2, note: 'canyon sandstone: beds, cross-bedding, honeycomb, joints (Blender, tools/blender/rockface.py)' },
];

const l2s = (v) => (v <= 0.0031308 ? v * 12.92 : 1.055 * Math.pow(v, 1 / 2.4) - 0.055);
const hex = (m) => m.reduce((h, v) => (h << 8) | Math.round(Math.min(1, l2s(v)) * 255), 0);
const bytes = {};
const mats = {};
for (const m of MATS) {
  const info = JSON.parse(readFileSync(join(BAKE, `${m.key}.json`), 'utf8'));
  mats[m.key] = { tiles: m.tiles, regular: false, mean: info.mean, hex: hex(info.mean), rough: info.rough, note: m.note };
  for (const S of SIZES) {
    // (ImageMagick 6 ignores -quality for WebP: a PSNR target, as the photoscan baker uses)
    for (const [ch, psnr] of [
      ['a', S >= 1024 ? 36 : 39],
      ['n', S >= 1024 ? 35 : 38],
    ]) {
      const src = join(BAKE, `${m.key}_${ch}_${S}.png`);
      const out = join(ROOT, `public/tex/terrain/${S}/${m.key}_${ch}.webp`);
      execFileSync('convert', [src, '-define', 'webp:lossless=false', '-define', 'webp:method=6', '-define', `webp:target-psnr=${psnr}`, '-define', 'webp:use-sharp-yuv=true', out]);
      const b = statSync(out).size;
      bytes[S] = (bytes[S] ?? 0) + b;
      mats[m.key][`b${S}`] = (mats[m.key][`b${S}`] ?? 0) + b;
      console.log(`${m.key}_${ch} ${S}: ${(b / 1024).toFixed(0)} KB (target ${psnr} dB)`);
    }
  }
}

// the kit: weld, quantise, meshopt (LOD meshes are separate primitives: <key>_hi / <key>_lo)
await MeshoptEncoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.encoder': MeshoptEncoder });
const doc = await io.read(join(BAKE, 'rockkit-raw.glb'));
await doc.transform(weld(), dedup(), prune(), quantize({ quantizePosition: 14, quantizeNormal: 10, quantizeColor: 8 }));
doc.createExtension(EXTMeshoptCompression).setRequired(true).setEncoderOptions({ method: EXTMeshoptCompression.EncoderMethod.QUANTIZE });
const glb = join(ROOT, 'public/tex/rocks/rockkit.glb');
writeFileSync(glb, await io.writeBinary(doc));
const kitBytes = statSync(glb).size;
const kit = JSON.parse(readFileSync(join(BAKE, 'rockkit.json'), 'utf8'));
console.log(`rockkit.glb: ${(kitBytes / 1024).toFixed(0)} KB`, JSON.stringify(kit));

const ts = `// GENERATED by tools/blender/rocks-pack.mjs (GD4) - do not edit by hand (re-run tools/blender/bake-rocks.sh).
// The desert's Blender-baked rock set: the rock-face detail maps (tools/blender/rockface.py), files
// public/tex/terrain/<size>/<key>_{a,n}.webp in the photoscans' packing (terrainset.ts), and the rock kit
// (tools/blender/rockkit.py), public/tex/rocks/rockkit.glb.
import type { PhotoMaterial } from './terrainset';

export const ROCK_FACES: Record<'dgranite' | 'dsandst', PhotoMaterial> = {
${Object.entries(mats)
  .map(([k, v]) => `  // ${v.note}\n  ${k}: { tiles: ${v.tiles}, regular: false, mean: [${v.mean.join(', ')}], hex: 0x${v.hex.toString(16).padStart(6, '0')}, rough: ${v.rough} },`)
  .join('\n')}
};

/** Download of the granite's two WebPs per texture size (the desert ground's rock layer). */
export const GRANITE_BYTES: Record<number, number> = { ${SIZES.map((S) => `${S}: ${mats.dgranite[`b${S}`]}`).join(', ')} };
/** Download of both rocks' WebPs per texture size. */
export const ROCK_FACE_BYTES: Record<number, number> = { ${SIZES.map((S) => `${S}: ${bytes[S]}`).join(', ')} };
/** The rock kit: meshes <key>_hi / <key>_lo, triangles per level of detail, download size. */
export const ROCK_KIT: { bytes: number; tris: Record<string, { hi: number; lo: number }> } = {
  bytes: ${kitBytes},
  tris: { ${Object.entries(kit)
    .map(([k, v]) => `${k}: { hi: ${v.hi}, lo: ${v.lo} }`)
    .join(', ')} },
};
`;
writeFileSync(join(ROOT, 'src/render/rockset.ts'), ts);
console.log('wrote src/render/rockset.ts', JSON.stringify(bytes));
