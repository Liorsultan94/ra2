#!/usr/bin/env node
/*
 * CF1: pack the Blender-built vehicle hulks for the game (tools/blender/hulkkit.py).
 *
 *   node tools/blender/hulks-pack.mjs <bake_dir>        (from web/; bake-hulks.sh runs both steps)
 *
 * <bake_dir>/hulks-raw.glb -> public/models/hulks.glb (welded, quantised, EXT_meshopt_compression) and
 * src/render/hulkset.ts (triangles, bounds in game axes, download size).
 */
import { mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS, EXTMeshoptCompression } from '@gltf-transform/extensions';
import { dedup, prune, quantize, weld } from '@gltf-transform/functions';
import { MeshoptEncoder } from 'meshoptimizer';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const BAKE = process.argv[2];
if (!BAKE) throw new Error('usage: hulks-pack.mjs <bake_dir>');
await MeshoptEncoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.encoder': MeshoptEncoder });
const doc = await io.read(join(BAKE, 'hulks-raw.glb'));
await doc.transform(weld(), dedup(), prune(), quantize({ quantizePosition: 14, quantizeNormal: 10, quantizeColor: 8 }));
doc.createExtension(EXTMeshoptCompression).setRequired(true).setEncoderOptions({ method: EXTMeshoptCompression.EncoderMethod.QUANTIZE });
mkdirSync(join(ROOT, 'public/models'), { recursive: true });
const glb = join(ROOT, 'public/models/hulks.glb');
writeFileSync(glb, await io.writeBinary(doc));
const bytes = statSync(glb).size;
const info = JSON.parse(readFileSync(join(BAKE, 'hulks.json'), 'utf8'));
console.log(`hulks.glb: ${(bytes / 1024).toFixed(0)} KB`, JSON.stringify(info));
// Blender (x, y, z up) -> game (x, y up, z right = -Blender y)
const ts = `// GENERATED by tools/blender/hulks-pack.mjs (CF1) - do not edit by hand (re-run tools/blender/bake-hulks.sh).
// The burnt-out vehicle hulks built in Blender (tools/blender/hulkkit.py), public/models/hulks.glb.
export const HULK_SET: { bytes: number; pieces: Record<string, { tris: number; min: number[]; max: number[] }> } = {
  bytes: ${bytes},
  pieces: {
${Object.entries(info)
  .map(([k, v]) => `    ${k}: { tris: ${v.tris}, min: [${v.min[0]}, ${v.min[2]}, ${-v.max[1]}], max: [${v.max[0]}, ${v.max[2]}, ${-v.min[1]}] },`)
  .join('\n')}
  },
};
`;
writeFileSync(join(ROOT, 'src/render/hulkset.ts'), ts);
console.log('wrote src/render/hulkset.ts');
