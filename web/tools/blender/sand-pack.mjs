#!/usr/bin/env node
/*
 * GD1: pack the Blender-baked desert sand layers (tools/blender/sand.py) for the game.
 *
 *   node tools/blender/sand-pack.mjs <bake_dir>        (from web/; bake-sand.sh runs both steps)
 *
 * <bake_dir>/<key>_{a,n}_<px>.png -> public/tex/terrain/<px>/<key>_{a,n}.webp (512 = phones / medium,
 * 1024 = high), the same packing and folders as the photoscans (tools/bake-terrain.mjs), and writes
 * src/render/sandset.ts: repeat scale, mean colour, roughness and download sizes of the two layers
 * (photoground.ts swaps them into the desert's texture arrays).
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const BAKE = process.argv[2];
if (!BAKE) throw new Error('usage: sand-pack.mjs <bake_dir>');
const SIZES = [512, 1024];
/** Map tiles per texture repeat (sand.py's pebble radii are in repeats). */
const MATS = [
  { key: 'dsand', tiles: 2.2, note: 'soft desert sand: grain, grit, faint lumps (Blender, tools/blender/sand.py)' },
  { key: 'dreg', tiles: 1.8, note: 'reg / desert pavement gravel half sunk in coarse sand (Blender, tools/blender/sand.py)' },
];

/** PSNR target (dB) for packed 8-bit RGB (tools/bake-terrain.mjs): error ~ 0.2 x the mean channel deviation, never below `floor`. */
function psnrFor(rgb, floor) {
  let sd = 0;
  for (let c = 0; c < 3; c++) {
    let m = 0;
    let m2 = 0;
    const n = rgb.length / 3;
    for (let k = c; k < rgb.length; k += 3) {
      m += rgb[k];
      m2 += rgb[k] * rgb[k];
    }
    m /= n;
    sd += Math.sqrt(Math.max(0, m2 / n - m * m)) / 3;
  }
  return Math.round(Math.min(48, Math.max(floor, 20 * Math.log10(255 / (0.2 * Math.max(1, sd))))));
}

const l2s = (v) => (v <= 0.0031308 ? v * 12.92 : 1.055 * Math.pow(v, 1 / 2.4) - 0.055);
const hex = (m) => m.reduce((h, v) => (h << 8) | Math.round(Math.min(1, l2s(v)) * 255), 0);
const bytes = {};
const mats = {};
for (const m of MATS) {
  const info = JSON.parse(readFileSync(join(BAKE, `${m.key}.json`), 'utf8'));
  mats[m.key] = { tiles: m.tiles, regular: false, mean: info.mean, hex: hex(info.mean), rough: info.rough, note: m.note };
  for (const S of SIZES) {
    for (const [ch, floor] of [
      ['a', S >= 1024 ? 35 : 36],
      ['n', S >= 1024 ? 33 : 34],
    ]) {
      const src = join(BAKE, `${m.key}_${ch}_${S}.png`);
      const out = join(ROOT, `public/tex/terrain/${S}/${m.key}_${ch}.webp`);
      // (ImageMagick 6 ignores -quality for WebP: a PSNR target as the photoscan baker uses)
      // (the sand's albedo varies so little that the deviation rule would ask for 45+ dB: 40 dB is already an
      // error of ~2.5 levels in 255)
      const rgb = execFileSync('convert', [src, '-depth', '8', 'rgb:-'], { maxBuffer: 1 << 28 });
      const psnr = Math.min(ch === 'a' ? 40 : 48, psnrFor(rgb, floor));
      execFileSync('convert', [src, '-define', 'webp:lossless=false', '-define', 'webp:method=6', '-define', `webp:target-psnr=${psnr}`, '-define', 'webp:use-sharp-yuv=true', out]);
      const b = statSync(out).size;
      bytes[S] = (bytes[S] ?? 0) + b;
      console.log(`${m.key}_${ch} ${S}: ${(b / 1024).toFixed(0)} KB (target ${psnr} dB)`);
    }
  }
}
// the dune scan the sand layer replaces (its bytes leave the desert's download)
const tj = JSON.parse(readFileSync(join(ROOT, 'public/tex/terrain/terrain.json'), 'utf8'));
const dunes = Object.fromEntries(SIZES.map((S) => [S, tj.materials.dunes.sizes[S].bytes]));
const fmt = (o) => `{ ${Object.entries(o).map(([k, v]) => `${k}: ${typeof v === 'string' ? JSON.stringify(v) : JSON.stringify(v)}`).join(', ')} }`;
const ts = `// GENERATED by tools/blender/sand-pack.mjs (GD1) - do not edit by hand (re-run tools/blender/bake-sand.sh).
// The desert's Blender-baked sand layers (tools/blender/sand.py): files public/tex/terrain/<size>/<key>_{a,n}.webp,
// same packing as the photoscans (terrainset.ts); photoground.ts swaps them into the desert's texture arrays.
import type { PhotoMaterial } from './terrainset';

export const SAND_MATERIALS: Record<'dsand' | 'dreg', PhotoMaterial> = {
${Object.entries(mats)
  .map(([k, m]) => `  // ${m.note}\n  ${k}: { tiles: ${m.tiles}, regular: false, mean: [${m.mean.join(', ')}], hex: 0x${m.hex.toString(16).padStart(6, '0')}, rough: ${m.rough} },`)
  .join('\n')}
};

/** Download of both layers (both WebPs each) per texture size. */
export const SAND_BYTES: Record<number, number> = ${fmt(bytes)};
/** Download of the dune scan they replace in the desert stack. */
export const DUNES_BYTES: Record<number, number> = ${fmt(dunes)};
`;
writeFileSync(join(ROOT, 'src/render/sandset.ts'), ts);
console.log('sandset.ts written', JSON.stringify(bytes));
